/** Normalized `@run-at` values, plus two non-standard extras. */
export type ScriptRunAt =
  | 'document-start'
  | 'document-body'
  | 'document-end'
  | 'document-idle'
  | 'context-menu'
  | 'early-start';

/** Where a script wants to execute. */
export type ScriptInjectInto = 'auto' | 'page' | 'content';

/** The world chosen for a concrete registration. */
export type ScriptWorld = 'MAIN' | 'USER_SCRIPT';

/** Raw metablock: tag -> all values, tag names lower-cased. */
export interface ScriptMetadata {
  [key: string]: string[] | undefined;
}

export type UrlRule =
  | { kind: 'match-include'; pattern: string }
  | { kind: 'match-exclude'; pattern: string }
  | { kind: 'glob-include'; pattern: string }
  | { kind: 'glob-exclude'; pattern: string }
  | { kind: 'regex-include'; source: string; flags: string }
  | { kind: 'regex-exclude'; source: string; flags: string };

export interface ScriptResourceRef {
  name: string;
  url: string;
}

/** Persisted script metadata/index record. Source code lives in its own store. */
export interface UserScript {
  uuid: string;
  name: string;
  namespace: string;
  version: string;
  description?: string;
  author?: string;
  homepage?: string;
  supportUrl?: string;
  icon?: string;
  antifeature?: string[];

  enabled: boolean;
  /** Set when moved to the recycle bin. */
  removedAt?: number;
  sort: number;

  createdAt: number;
  updatedAt: number;
  lastRunAt?: number;
  runCount: number;

  /** URL the script was installed from. */
  origin: string;
  downloadUrl?: string;
  updateUrl?: string;
  checkUpdate: boolean;
  updateIntervalHours?: number;
  updateState: 'idle' | 'checking' | 'update-available' | 'error';
  pendingInstallToken?: string;
  pendingVersion?: string;
  lastError?: string;

  metadata: ScriptMetadata;
  /** User overrides. Only present keys differ from `metadata`. */
  selfMetadata?: ScriptMetadata;

  tags: string[];
  grant: string[];
  connect: string[];
  require: string[];
  resource: string[];

  runAt: ScriptRunAt;
  injectInto: ScriptInjectInto;
  noFrames: boolean;
  unwrap: boolean;
  topLevelAwait: boolean;

  codeHash: string;
  codeSize: number;
}

export interface ScriptVersion {
  /** `${uuid}:${timestamp}` */
  id: string;
  uuid: string;
  code: string;
  metadata: ScriptMetadata;
  createdAt: number;
}

/**
 * Cached identity icon for a script.
 *
 * Icons are fetched once (install/save/popup) and stored as a data URL in
 * IndexedDB: the popup must paint instantly and keep working offline, and a
 * remote favicon URL in `chrome.storage` would grow without bound. `source`
 * pins the cache to the current `@icon` value so an edited icon refetches.
 */
export interface ScriptIconCache {
  uuid: string;
  source: string;
  /** Present only for a successful fetch. */
  dataUrl?: string;
  /** Last attempt (success or failure); drives TTL and retry backoff. */
  fetchedAt: number;
  failed?: boolean;
}

export interface StoredResource {
  uuid: string;
  url: string;
  name: string;
  kind: 'require' | 'require-css' | 'resource';
  content: string;
  contentType: string;
  base64?: string;
  hash: string;
  fetchedAt: number;
}

export interface RuntimeResource {
  name: string;
  url: string;
  content: string;
  contentType: string;
  base64?: string;
}

export interface ScriptBootstrap {
  values: Record<string, unknown>;
  resources: Record<string, RuntimeResource>;
}

/** The serializable payload embedded in a generated userScript launcher. */
export interface RuntimeScriptPayload {
  uuid: string;
  /**
   * HMAC token proving this launcher was generated by the background for this
   * script and world. Verified on every host RPC.
   */
  runtimeToken: string;
  name: string;
  namespace: string;
  version: string;
  description?: string;
  metaStr: string;
  meta: ScriptMetadata;
  handlerVersion: string;
  grant: string[];
  connect: string[];
  rules: UrlRule[];
  code: string;
  /** Concatenated @require sources, already fetched and cached. */
  requires: string[];
  requireCss: string[];
  /** Names available to GM_getResourceText/URL. */
  resourceNames: string[];
  runAt: ScriptRunAt;
  injectInto: 'page' | 'content';
  noFrames: boolean;
  unwrap: boolean;
  contextMenu: boolean;
  /** Injected by the launcher at runtime. */
  run?: (GM: any, GM_info: any, unsafeWindow: any) => Promise<void>;
}

