#!/usr/bin/env node
/**
 * Translation context report.
 *
 * Prints every canonical key next to the component call sites that render it.
 * A translator needs the *role* of a string (button, hint, aria label, toast)
 * to choose the right grammatical form; a flat key/value table cannot express
 * that. Output is Markdown, intended for `docs/i18n-context.md`.
 */
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const en = JSON.parse(readFileSync(join(root, 'i18n/locales/en.json'), 'utf8'));

function flatten(value, prefix = '', out = new Map()) {
  if (value && typeof value === 'object') {
    for (const [key, child] of Object.entries(value)) {
      flatten(child, prefix ? `${prefix}.${key}` : key, out);
    }
  } else {
    out.set(prefix, String(value));
  }
  return out;
}

const values = flatten(en);
const sites = new Map();

function walk(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (/\.tsx?$/.test(entry.name)) out.push(full);
  }
  return out;
}

const namespace = /^(?:common|app|popup|options|scripts|metadata|editor|settings|logs|install|errors|diagnostics)\./;

for (const dir of ['components', 'entrypoints', 'lib']) {
  for (const file of walk(join(root, dir))) {
    const source = readFileSync(file, 'utf8');
    const sf = ts.createSourceFile(
      file,
      source,
      ts.ScriptTarget.Latest,
      true,
      file.endsWith('x') ? ts.ScriptKind.TSX : ts.ScriptKind.TS,
    );
    const visit = (node) => {
      if (ts.isStringLiteral(node) && namespace.test(node.text)) {
        const line = sf.getLineAndCharacterOfPosition(node.getStart(sf)).line + 1;
        const where = `${relative(root, file)}:${line}`;
        if (!sites.has(node.text)) sites.set(node.text, new Set());
        sites.get(node.text).add(where);
      }
      ts.forEachChild(node, visit);
    };
    visit(sf);
  }
}

const rows = [...values.entries()].sort(([a], [b]) => a.localeCompare(b));
console.log('# i18n context');
console.log('');
console.log('Generated by `npm run i18n:context`. One row per canonical key.');
console.log('');
console.log('| Key | English | Call sites |');
console.log('| --- | --- | --- |');
for (const [key, value] of rows) {
  const refs = [...(sites.get(key) ?? [])].sort().join('<br>') || '—';
  const text = value.replace(/\|/g, '\\|').replace(/\n/g, ' ');
  console.log(`| \`${key}\` | ${text} | ${refs} |`);
}
